#requires -Version 5.1
[CmdletBinding()]
param([string]$OutputPath)
$ErrorActionPreference='Stop'
Set-StrictMode -Version 2.0
$repo=Split-Path -Parent $PSScriptRoot
if(-not$OutputPath){$OutputPath=Join-Path $repo 'acceptance/TaskPilot.Acceptance.ps1'}
$source=[IO.File]::ReadAllText((Join-Path $repo 'TaskPilot.ps1'))
$bodyMarker='$LocalAppData = $script:TPRuntimeContext.ProfileRoot'
$index=$source.IndexOf($bodyMarker,[StringComparison]::Ordinal)
if($index-lt0-or$source.IndexOf($bodyMarker,$index+1,[StringComparison]::Ordinal)-ge0){throw 'Acceptance entry generation requires exactly one known runtime body marker.'}
$body=$source.Substring($index)
$legacy='$LegacyRoot = if ($script:TPRuntimeContext.IsTestMode) { $null } else { Join-Path $LocalAppData ''TaskPilot'' }'
if(-not$body.Contains($legacy)){throw 'The reviewed legacy assignment changed; inspect before regenerating acceptance entry.'}
$body=$body.Replace($legacy,'$LegacyRoot = $null # Acceptance never selects, checks, or migrates legacy data.')
$adapter='. (Join-Path $InstallRoot ''Adapters/TaskPilot.GuiStartup.ps1'')'
if(-not$body.Contains($adapter)){throw 'The reviewed adapter insertion marker changed.'}
$body=$body.Replace($adapter,$adapter+"`r`n"+'. (Join-Path $InstallRoot ''acceptance/TaskPilot.Acceptance.Gui.ps1'')'+"`r`n"+'. (Join-Path $InstallRoot ''acceptance/TaskPilot.Acceptance.Diagnostics.ps1'')')
$cleanup='finally { if(Get-Command Close-TPRuntime -ErrorAction SilentlyContinue){Close-TPRuntime} }'
if(-not$body.Contains($cleanup)){throw 'The reviewed runtime disposal marker changed.'}
$body=$body.Replace($cleanup,'finally { Close-TPDesktopAcceptanceRuntime }')
$prefix=@'
#requires -Version 5.1
# Generated by tools/New-TaskPilotDesktopAcceptanceEntry.ps1. Dedicated GUI only.
[CmdletBinding(PositionalBinding=$false)]
param()
$ErrorActionPreference='Stop'
if($args.Count-ne0){throw 'TP-ACCEPTANCE-ARGUMENTS-FORBIDDEN'}
$launcher='TaskPilot.Acceptance.Launcher' -as [type]
if($null-eq$launcher-or-not$launcher.GetProperty('IsDedicatedLauncher').GetValue($null,$null)){
    throw 'TP-ACCEPTANCE-DEDICATED-LAUNCHER-REQUIRED'
}
# The signed native launcher pins and verifies this script and Security.ps1
# before entering this runspace. A standalone PowerShell invocation is denied.
$InstallRoot=[IO.Path]::GetFullPath((Split-Path -Parent $PSScriptRoot))
. (Join-Path $InstallRoot 'acceptance/TaskPilot.Acceptance.Security.ps1')
$bootstrapAuthority=Open-TPAcceptanceAuthorization -PackageRoot $InstallRoot
try{
    $null=$bootstrapAuthority.PackageLease.AssertPinned('Runtime/TaskPilot.Runtime.ps1')
    . ($bootstrapAuthority.PackageLease.FullPath('Runtime/TaskPilot.Runtime.ps1'))
    $null=$bootstrapAuthority.PackageLease.AssertPinned('acceptance/TaskPilot.Acceptance.Runtime.ps1')
    . ($bootstrapAuthority.PackageLease.FullPath('acceptance/TaskPilot.Acceptance.Runtime.ps1'))
    $script:TPRuntimeContext=Initialize-TPDesktopAcceptanceRuntime -InstallRoot $InstallRoot
}finally{$bootstrapAuthority.Dispose()}
'@
$text=($prefix+"`r`n"+$body)-replace"`r?`n","`r`n"
$tokens=$null;$errors=$null
$null=[Management.Automation.Language.Parser]::ParseInput($text,[ref]$tokens,[ref]$errors)
if($errors.Count-ne0){throw 'Generated acceptance entry failed PowerShell parsing.'}
$full=[IO.Path]::GetFullPath($OutputPath)
$parent=Split-Path -Parent $full
if(-not[IO.Directory]::Exists($parent)){throw 'Acceptance generation requires an existing output directory.'}
if([IO.File]::Exists($full)-and([IO.File]::GetAttributes($full)-band[IO.FileAttributes]::ReparsePoint)){throw 'Acceptance output must not be a link.'}
[IO.File]::WriteAllText($full,$text,[Text.UTF8Encoding]::new($true))
[pscustomobject]@{Path=$full;Source='TaskPilot.ps1';DedicatedAcceptanceEntry=$true;ArgumentsSupported=$false;GeneralRuntimeChanged=$false}
