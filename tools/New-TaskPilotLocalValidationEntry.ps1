#requires -Version 5.1
[CmdletBinding()]
param([string]$OutputPath)
$ErrorActionPreference='Stop'
Set-StrictMode -Version 2.0
$repo=Split-Path -Parent $PSScriptRoot
if(-not$OutputPath){$OutputPath=Join-Path $repo 'local-validation/TaskPilot.LocalValidation.ps1'}
$source=([IO.File]::ReadAllText((Join-Path $repo 'TaskPilot.ps1')))-replace"`r?`n","`r`n"
$bodyMarker='$LocalAppData = $script:TPRuntimeContext.ProfileRoot'
$index=$source.IndexOf($bodyMarker,[StringComparison]::Ordinal)
if($index-lt0-or$source.IndexOf($bodyMarker,$index+1,[StringComparison]::Ordinal)-ge0){throw 'Local validation entry generation requires exactly one known runtime body marker.'}
$body=$source.Substring($index)
$legacy='$LegacyRoot = if ($script:TPRuntimeContext.IsTestMode) { $null } else { Join-Path $LocalAppData ''TaskPilot'' }'
if(-not$body.Contains($legacy)){throw 'The reviewed legacy assignment changed; inspect before regenerating local validation entry.'}
$body=$body.Replace($legacy,'$LegacyRoot = $null # Local validation never selects, checks, or migrates legacy data.')
$adapter='. (Join-Path $InstallRoot ''Adapters/TaskPilot.GuiStartup.ps1'')'
if(-not$body.Contains($adapter)){throw 'The reviewed adapter insertion marker changed.'}
$body=$body.Replace($adapter,$adapter+"`r`n"+'. (Join-Path $InstallRoot ''local-validation/TaskPilot.LocalValidation.Gui.ps1'')'+"`r`n"+'. (Join-Path $InstallRoot ''local-validation/TaskPilot.LocalValidation.Diagnostics.ps1'')')
$originalStartupCatch=@'
} catch {
    if(Get-Command Show-Failure -ErrorAction SilentlyContinue){Show-Failure $_}
    else{Write-ErrorLog $_;[System.Windows.Forms.MessageBox]::Show($_.Exception.Message,'TaskPilot 起動エラー',[System.Windows.Forms.MessageBoxButtons]::OK,[System.Windows.Forms.MessageBoxIcon]::Error)|Out-Null}
} finally {
'@ -replace"`r?`n","`r`n"
$acceptanceStartupCatch=@'
} catch {
    # Unique early-installed helper: never call a partially loaded GUI adapter's
    # error handler or forward ErrorRecord, task content, paths or exceptions.
    Show-TPLocalValidationStartupFailure
} finally {
'@ -replace"`r?`n","`r`n"
if(-not$body.Contains($originalStartupCatch)){throw 'The reviewed startup failure handler changed; inspect before regenerating local validation entry.'}
$body=$body.Replace($originalStartupCatch,$acceptanceStartupCatch)
$cleanup='finally { if(Get-Command Close-TPRuntime -ErrorAction SilentlyContinue){Close-TPRuntime} }'
if(-not$body.Contains($cleanup)){throw 'The reviewed runtime disposal marker changed.'}
$body=$body.Replace($cleanup,'finally { Close-TPLocalValidationRuntime }')
$prefix=@'
#requires -Version 5.1
# Generated by tools/New-TaskPilotLocalValidationEntry.ps1. Local developer GUI only.
[CmdletBinding(PositionalBinding=$false)]
param()
$ErrorActionPreference='Stop'
if($args.Count-ne0){throw 'TP-LOCAL-ARGUMENTS-FORBIDDEN'}
$nativeHost='TaskPilot.LocalValidation.Host'-as[type]
if($null-eq$nativeHost){throw 'TP-LOCAL-DEDICATED-HOST-REQUIRED'}
foreach($propertyName in @('IsLocalValidationHost','HasProtectedParent','PackageRoot')){
    if($null-eq$nativeHost.GetProperty($propertyName)){throw 'TP-LOCAL-DEDICATED-HOST-REQUIRED'}
}
if(-not$nativeHost::IsLocalValidationHost-or-not$nativeHost::HasProtectedParent-or
   $null-eq$nativeHost.GetMethod('OpenCurrentSession')){throw 'TP-LOCAL-PROTECTED-PARENT-REQUIRED'}
# The already-admitted native host owns the protected parent session and package
# boundary. No standalone script, caller approval Boolean or mode switch is valid.
$InstallRoot=[IO.Path]::GetFullPath((Split-Path -Parent $PSScriptRoot))
if(-not[string]::Equals($InstallRoot,$nativeHost::PackageRoot,[StringComparison]::OrdinalIgnoreCase)){throw 'TP-LOCAL-PACKAGE-ROOT'}
$bootstrapSession=$nativeHost::OpenCurrentSession()
if($null-eq$bootstrapSession){throw 'TP-LOCAL-SESSION-INVALID'}
try{
    if($bootstrapSession.Purpose-cne'LocalDeveloperValidationSyntheticOnly'-or$bootstrapSession.Version-cne'0.4.0.2'){
        throw 'TP-LOCAL-SESSION-INVALID'
    }
    $null=$bootstrapSession.PackageLease.AssertPinned('Runtime/TaskPilot.Runtime.ps1')
    . ($bootstrapSession.PackageLease.FullPath('Runtime/TaskPilot.Runtime.ps1'))
    $null=$bootstrapSession.PackageLease.AssertPinned('local-validation/TaskPilot.LocalValidation.Runtime.ps1')
    . ($bootstrapSession.PackageLease.FullPath('local-validation/TaskPilot.LocalValidation.Runtime.ps1'))
    $script:TPRuntimeContext=Initialize-TPLocalValidationRuntime -InstallRoot $InstallRoot
    # Content-free handlers are installed before any GUI adapter and again last.
    $null=$script:TPRuntimeContext.LocalSession.PackageLease.AssertPinned('local-validation/TaskPilot.LocalValidation.Diagnostics.ps1')
    . ($script:TPRuntimeContext.LocalSession.PackageLease.FullPath('local-validation/TaskPilot.LocalValidation.Diagnostics.ps1'))
}finally{$bootstrapSession.Dispose()}
'@
$text=($prefix+"`r`n"+$body)-replace"`r?`n","`r`n"
$tokens=$null;$errors=$null
$null=[Management.Automation.Language.Parser]::ParseInput($text,[ref]$tokens,[ref]$errors)
if($errors.Count-ne0){throw 'Generated local validation entry failed PowerShell parsing.'}
$full=[IO.Path]::GetFullPath($OutputPath)
$parent=Split-Path -Parent $full
if(-not[IO.Directory]::Exists($parent)){throw 'Local validation generation requires an existing output directory.'}
if([IO.File]::Exists($full)-and([IO.File]::GetAttributes($full)-band[IO.FileAttributes]::ReparsePoint)){throw 'Local validation output must not be a link.'}
[IO.File]::WriteAllText($full,$text,[Text.UTF8Encoding]::new($true))
[pscustomobject]@{Path=$full;Source='TaskPilot.ps1';DedicatedLocalValidationEntry=$true;ArgumentsSupported=$false;GeneralRuntimeChanged=$false}
